class L10nScope extends InheritedWidget {
  final String code;
  const L10nScope({super.key, required this.code, required super.child});

  static String of(BuildContext context) =>
      context.dependOnInheritedWidgetOfExactType<L10nScope>()?.code ?? 'th';

  @override
  bool updateShouldNotify(L10nScope old) => old.code != code;
}

int _index(BuildContext context) => switch (L10nScope.of(context)) { 'en' => 1, 'zh' => 2, _ => 0 };

String t(BuildContext context, String key) => _l10n[key]?[_index(context)] ?? key;

String tf(BuildContext context, String key, Map<String, String> vars) {
  var s = t(context, key);
  for (final e in vars.entries) {
    s = s.replaceAll('{${e.key}}', e.value);
  }
  return s;
}

/// Translates a known server message; unknown text is shown as-is.
String localizeError(BuildContext context, String message) {
  final key = _serverMsg[message] ?? (_l10n.containsKey(message) ? message : null);
  return key == null ? message : t(context, key);
}

